"use client"

import * as React from "react"
import { Copy, QrCode, X } from "lucide-react"

import { Button } from "@/components/ui/button"

type InterviewQrCodeProps = {
  href: string
}

export function InterviewQrCode({ href }: InterviewQrCodeProps) {
  const [isOpen, setIsOpen] = React.useState(false)
  const [copied, setCopied] = React.useState(false)
  const [url, setUrl] = React.useState("")

  React.useEffect(() => {
    if (!isOpen) return

    function closeOnEscape(event: KeyboardEvent) {
      if (event.key === "Escape") setIsOpen(false)
    }

    window.addEventListener("keydown", closeOnEscape)
    return () => window.removeEventListener("keydown", closeOnEscape)
  }, [isOpen])

  async function copyLink() {
    if (!url) return
    await navigator.clipboard.writeText(url)
    setCopied(true)
    window.setTimeout(() => setCopied(false), 1800)
  }

  function openDialog() {
    setUrl(new URL(href, window.location.origin).toString())
    setIsOpen(true)
  }

  return (
    <>
      <Button type="button" variant="outline" onClick={openDialog}>
        <QrCode />
        Scan on mobile
      </Button>

      {isOpen && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4"
          role="presentation"
          onMouseDown={(event) => {
            if (event.target === event.currentTarget) setIsOpen(false)
          }}
        >
          <section
            aria-labelledby="interview-qr-title"
            aria-modal="true"
            className="relative flex w-full max-w-sm flex-col items-center gap-4 rounded-xl bg-background p-6 text-center shadow-xl"
            role="dialog"
          >
            <button
              type="button"
              aria-label="Close QR code"
              className="absolute right-3 top-3 rounded p-1 text-muted-foreground hover:bg-muted"
              onClick={() => setIsOpen(false)}
            >
              <X className="size-4" />
            </button>
            <div>
              <h2 id="interview-qr-title" className="text-lg font-semibold">
                Open interview capture on mobile
              </h2>
              <p className="mt-1 text-sm text-muted-foreground">
                Scan this code with your phone&apos;s camera. You may need to sign in.
              </p>
            </div>
            {url ? (
              // The QR image is generated by QRServer; it encodes only this page URL.
              // eslint-disable-next-line @next/next/no-img-element
              <img
                alt="QR code linking to interview capture"
                className="size-60 rounded border bg-white p-2"
                height={240}
                src={`https://api.qrserver.com/v1/create-qr-code/?size=240x240&data=${encodeURIComponent(url)}`}
                width={240}
              />
            ) : (
              <div className="size-60 animate-pulse rounded bg-muted" />
            )}
            <div className="flex w-full gap-2">
              <Button type="button" variant="outline" className="flex-1" onClick={copyLink}>
                <Copy />
                {copied ? "Copied" : "Copy link"}
              </Button>
              {url && (
                <a
                  href={url}
                  target="_blank"
                  rel="noreferrer"
                  className="inline-flex flex-1 items-center justify-center rounded-lg bg-primary px-3 py-2 text-sm font-medium text-primary-foreground hover:bg-primary/90"
                >
                  Open link
                </a>
              )}
            </div>
          </section>
        </div>
      )}
    </>
  )
}
